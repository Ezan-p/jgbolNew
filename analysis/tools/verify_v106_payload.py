"""Check release payload, generated Lua and old-save compatibility in isolation."""
import hashlib
import io
import json
from pathlib import Path
import sqlite3
import subprocess
import sys
import time
import zipfile

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from offline_android.pack_payload import collect_files, verify_payload
from analysis.tools.verify_v105_update import WORKER, database_snapshot

WORK = ROOT / '.runtime/v106-build'
EVIDENCE = ROOT / 'analysis/evidence/v106'
BASE = ROOT / 'build/金箍棒3.87-离线单机-arm32-v105-封神榜修复.apk'
APK = ROOT / 'build/金箍棒3.87-离线单机-arm32-v106.apk'


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main(allowed_new_cortege_fields=()):
    trees = {}
    for mode, apk in [('old', BASE), ('new', APK)]:
        tree = WORK / ('payload-' + mode)
        with zipfile.ZipFile(apk) as archive, \
                zipfile.ZipFile(io.BytesIO(archive.read('assets/offline/program.zip'))) as program:
            assert program.testzip() is None
            assert not any(Path(n).suffix in ('.db', '.sqlite3', '.pyc') or
                           'save' in Path(n).parts for n in program.namelist())
            program.extractall(tree)
        verify_payload(tree)
        trees[mode] = tree
    checked = 0
    for name, path in collect_files().items():
        if name == 'network_redirect/login.html':
            continue  # Android-specific wording, generated by the existing packer.
        assert digest(path) == digest(trees['new'] / name), name
        checked += 1
    from network_redirect import summon
    assert (trees['new'] / 'offline_client.lua').read_text() == summon.client_source(summon.load_rules())
    for name in ('offline_android/backend.py', 'server_config/formation_rules.json',
                 'server_config/gift_code_rules.json', 'network_redirect/formation.py'):
        assert (trees['old'] / name).read_bytes() == (trees['new'] / name).read_bytes(), name
    codes = json.loads((trees['new'] / 'server_config/gift_code_rules.json').read_text())
    source = ROOT / '.runtime/opening-qa/after-all-tests.sqlite3'
    source_hash = digest(source)
    save = WORK / 'save-compatibility'
    save.mkdir(exist_ok=True)
    database = save / 'game.sqlite3'
    with sqlite3.connect(source.as_uri() + '?mode=ro', uri=True) as old, sqlite3.connect(database) as copy:
        old.backup(copy)
    frozen_time = str(int(time.time()))
    passes = []
    expected = None
    added_fields = 0
    exact_tables = True
    for mode in ('old', 'new', 'new'):
        result = subprocess.run([sys.executable, '-I', '-c', WORKER, str(trees[mode]),
                                 str(save), frozen_time], capture_output=True, text=True, timeout=90)
        assert result.returncode == 0, result.stderr
        passes.append(dict(mode=mode, **json.loads(result.stdout)))
        snapshot = database_snapshot(database)
        if expected is None:
            expected = snapshot
        else:
            if snapshot != expected and allowed_new_cortege_fields and len(passes) == 2:
                # An explicit additive migration may initialize new feature fields.
                # Compare every original value; never ignore or rewrite old fields.
                normalized = dict(snapshot)
                rows = []
                assert len(snapshot['roles']) == len(expected['roles'])
                for old_row, new_row in zip(expected['roles'], snapshot['roles']):
                    old_role, new_role = json.loads(old_row[1]), json.loads(new_row[1])
                    assert len(old_role['corteges']) == len(new_role['corteges'])
                    for old_c, new_c in zip(old_role['corteges'], new_role['corteges']):
                        for key in set(new_c) - set(old_c):
                            assert key in allowed_new_cortege_fields and type(new_c[key]) is int and new_c[key] == 0, key
                            del new_c[key]
                            added_fields += 1
                    assert new_role == old_role, 'Existing role values changed during migration'
                    rows.append((new_row[0], old_row[1], *new_row[2:]))
                normalized['roles'] = rows
                assert normalized == expected, 'Non-role database content changed during migration'
                exact_tables = False
                expected = snapshot  # Restart must preserve even the added fields exactly.
            else:
                assert snapshot == expected, 'Unexpected saved data change on upgrade/restart'
    assert digest(source) == source_hash
    # Execute the real new adapters from the extracted APK, not source copies.
    from lupa.lua51 import LuaRuntime
    vm = LuaRuntime()
    vm.execute('assert(loadstring(...))', (trees['new'] / 'offline_client.lua').read_text())
    trial = vm.execute((ROOT / 'tests/trial_client_regression.lua').read_text(),
                      (trees['new'] / 'network_redirect/trial_client.lua').read_text())
    sweep_vm = LuaRuntime()
    sweep = sweep_vm.execute((ROOT / 'tests/rape_sweep_client_regression.lua').read_text(),
                             (trees['new'] / 'network_redirect/rape_client.lua').read_text())
    source_worker = r'''
import pathlib, sys
sys.path.insert(0, sys.argv[1])
sys.path.insert(1, sys.argv[2])
from network_redirect import summon, activity_moon, activity_rice
assert pathlib.Path(summon.__file__).resolve().is_relative_to(pathlib.Path(sys.argv[1]))
from lupa.lua51 import LuaRuntime
vm = LuaRuntime()
rules = __import__('network_redirect.activity', fromlist=['load_rules']).load_rules()
checks = vm.execute(pathlib.Path(sys.argv[3]).read_text(), activity_moon.client_source(rules), activity_rice.client_source(rules))
print(checks)
'''
    result = subprocess.run([sys.executable, '-I', '-c', source_worker, str(trees['new']),
        '/private/tmp/jgbol-rank-lua', str(ROOT / 'tests/seasonal_craft_client_regression.lua')],
        capture_output=True, text=True, timeout=90)
    assert result.returncode == 0, result.stderr
    seasonal_checks = result.stdout.strip()
    inventory_vm = LuaRuntime()
    inventory_vm.execute('''
local bag={sortProps=function(a,b) return a.csvInfo.sortOrder<b.csvInfo.sortOrder end}
package.loaded.ms={d_packageUI=bag}
assert(loadstring(...))()
local rows={{type_id=1307,csvInfo={sortOrder=100}}, {type_id=1304,csvInfo={sortOrder=305}},
 {type_id=1306,csvInfo={sortOrder=307}}, {type_id=1305,csvInfo={sortOrder=306}},
 {type_id=1041,csvInfo={sortOrder=306}}, {type_id=1001,csvInfo={sortOrder=10}}}
table.sort(rows,bag.sortProps)
for i=1,4 do assert(rows[i+1].type_id==1303+i) end
bag._localInventoryRestore()
table.sort(rows,bag.sortProps)
assert(rows[2].type_id==1307)
''', (trees['new'] / 'network_redirect/inventory_client.lua').read_text())
    handbook_vm = LuaRuntime()
    handbook = handbook_vm.execute((ROOT / 'tests/handbook_client_regression.lua').read_text(),
        (trees['new'] / 'network_redirect/skill_client.lua').read_text())
    skill_vm = LuaRuntime()
    skill_checks = skill_vm.execute((ROOT / 'tests/skill_client_regression.lua').read_text().replace(
        '-- INSTALL_PATCH', (trees['new'] / 'network_redirect/skill_client.lua').read_text()))
    report = dict(apk_sha256=digest(APK), baseline_sha256=digest(BASE),
        all_payload_hashes_verified=True, current_source_files_verified=checked,
        generated_client_matches=True, lua51_full_bundle_compiles=True,
        trial_lua_checks=len(trial), sweep_lua_checks=len(sweep),
        seasonal_lua_checks=seasonal_checks, inventory_sort_and_restore_pass=True,
        handbook_lua_checks=len(handbook),
        existing_skill_lua_checks=len(skill_checks),
        gift_codes_preserved=len(codes['codes']), potential_rules_and_migration_preserved=True,
        rank_hotfix_preserved=True, save_backend_unchanged=True, contains_player_database=False,
        all_database_tables_equal_after_upgrade_and_restart=exact_tables,
        all_existing_database_values_preserved=True,
        added_zero_feature_fields=added_fields,
        all_database_tables_equal_after_restart=True,
        source_qa_save_unchanged=True, save_load_passes=passes)
    (EVIDENCE / 'payload-save-validation.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
